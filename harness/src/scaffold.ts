// scaffold.ts — renders the app's topology FROM THE BILL, starting from the CCoE
// templates (core-platform/templates/). A brick that was not bought is not
// "commented out": it is absent — no worker service, no REDIS_URL, no flag.
// These files are harness-owned (the hook refuses builder edits); change the
// bill, not the YAML.
import { chmodSync, copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { HARNESS_DIR } from "./catalog";
import type { Bill, Brief } from "./needs";
import { ownedBricks } from "./needs";

const HEADER = (what: string) => `# ${what} — GENERATED by \`harness plan\` from .harness/bill.yaml.
# Harness-owned: the PreToolUse hook refuses builder edits. To change the
# topology, change a requirement and re-plan — the bill decides, not this file.
`;

/** The ports convention: one block of 10 in 8000–8999 per app — checked against the sibling apps, or the first free one. */
export function portBlock(appDir: string, requested?: number): number {
  const taken = new Map<number, string>();
  const parent = dirname(appDir);
  for (const d of readdirSync(parent, { withFileTypes: true })) {
    const ci = join(parent, d.name, ".gitlab-ci.yml");
    if (!d.isDirectory() || join(parent, d.name) === appDir || !existsSync(ci)) continue;
    const port = Number((Bun.YAML.parse(readFileSync(ci, "utf8")) as { variables?: Record<string, string> })?.variables?.FRONTEND_PORT);
    if (port >= 8000 && port <= 8999) taken.set(Math.floor(port / 10) * 10, d.name);
  }
  if (requested !== undefined) {
    if (requested < 8000 || requested > 8990 || requested % 10 !== 0) throw new Error(`port_block ${requested}: a multiple of 10 in 8000–8990 (README → the ports convention)`);
    if (taken.has(requested)) throw new Error(`port_block ${requested} is already ${taken.get(requested)}'s — pick another block`);
    return requested;
  }
  for (let b = 8000; b <= 8990; b += 10) if (!taken.has(b)) return b;
  throw new Error("no free port block left in 8000–8999");
}

export function composeYml(brief: Brief, bill: Bill): string {
  const owned = new Set(ownedBricks(bill));
  const env = [
    "  VAULT_ADDR: http://openbao.internal:8200",
    "  VAULT_TOKEN: root-dev-token",
    "  VAULT_PATH: secret/${APP}",
    "  DB_HOST: postgres.internal",
    '  DB_PORT: "5432"',
    "  DB_NAME: ${APP}",
  ];
  if (owned.has("valkey")) env.push("  REDIS_URL: redis://valkey.internal:6379");
  if (owned.has("s3")) env.push("  S3_ENDPOINT: http://host.containers.internal:9000", "  S3_BUCKET: ${APP}", "  S3_REGION: us-east-1");
  const svc: string[] = [];
  if (owned.has("frontend")) {
    svc.push(`  frontend:
    image: localhost:5000/\${APP}/frontend:\${TAG:-dev}
    container_name: \${APP}-frontend
    restart: unless-stopped
    networks: [core-network]
    depends_on: [api]
    ports:
      - "\${FRONTEND_PORT:-${brief.port_block}}:80"`);
  }
  svc.push(`  api:
    image: localhost:5000/\${APP}/api:\${TAG:-dev}
    container_name: \${APP}-api
    restart: unless-stopped
    networks: [core-network]
    environment: *common-env
    stop_grace_period: 10s
    ports:
      - "\${API_PORT:-${(brief.port_block ?? 8000) + 1}}:8080"
    healthcheck:
      test: ["CMD", "wget", "-qO-", "http://localhost:8080/ready"]
      interval: 10s
      timeout: 2s
      retries: 3
      start_period: 20s`);
  if (owned.has("worker")) {
    svc.push(`  worker:
    image: localhost:5000/\${APP}/worker:\${TAG:-dev}
    container_name: \${APP}-worker
    restart: unless-stopped
    networks: [core-network]
    environment: *common-env
    ports:
      - "\${WORKER_HEALTH_PORT:-${(brief.port_block ?? 8000) + 8}}:8081"`);
  }
  return `${HEADER("podman-compose.yml")}
name: \${APP}

networks:
  core-network:
    external: true

x-common-env: &common-env
${env.join("\n")}

services:
${svc.join("\n\n")}
`;
}

export function gitlabCiYml(brief: Brief, bill: Bill): string {
  const owned = new Set(ownedBricks(bill));
  const flag = (f: string) => (bill.flags.some((x) => x.startsWith(`${f}=`)) ? '"1"' : '"0"');
  const services = ["frontend", "api", "worker"].filter((s) => owned.has(s));
  const tsServices = services.filter((s) => s !== "frontend");
  const p = brief.port_block ?? 8000;
  const personas = brief.personas.map((x) => x.slug).join(" ");
  const ready = [owned.has("frontend") ? `http://localhost:$FRONTEND_PORT/` : "", `http://localhost:$API_PORT/ready`, owned.has("worker") ? `http://localhost:$WORKER_HEALTH_PORT/ready` : ""].filter(Boolean);
  return `${HEADER(".gitlab-ci.yml")}# The CCoE app pipeline (core-platform/templates/gitlab-ci.yml), pruned to the
# services the bill paid for, plus the harness gates: fitness (guards, before
# the build) and the platform onboarding the decisions call for.
#
#   gitlab-ci-local --force-shell-executor                          # start
#   gitlab-ci-local --force-shell-executor --variable ACTION=stop   # stop

stages: [app-provision, app-gates, app-build, app-image, app-deploy, app-verify, app-stop]

variables:
  APP: ${brief.app}
  TAG: dev
  REGISTRY: localhost:5000
  PUBLIC_BUCKET: ${flag("PUBLIC_BUCKET")}
  LLM_VKEY: ${flag("LLM_VKEY")}
  TEMPORAL_NS: ${flag("TEMPORAL_NS")}
  ANALYTICS_SITE: ${flag("ANALYTICS_SITE")}
  ACTION: start
  FRONTEND_PORT: "${p}"
  API_PORT: "${p + 1}"
  WORKER_HEALTH_PORT: "${p + 8}"
  BAO_CONTAINER: openbao.internal
  CORE_PLATFORM: ../core-platform
  HARNESS: ../harness

.on-start:
  rules:
    - if: $ACTION == "start"

.gate:
  extends: .on-start
  stage: app-gates
  variables:
    SERVICES: "${tsServices.join(" ")}"

.podman-image:
  extends: .on-start
  stage: app-image
  script:
    - podman build -t "$REGISTRY/$APP/$SERVICE:$TAG" "$SERVICE/"
    - podman push --tls-verify=false "$REGISTRY/$APP/$SERVICE:$TAG"

provision:
  extends: .on-start
  stage: app-provision
  script:
    - APP="$APP" PUBLIC_BUCKET="$PUBLIC_BUCKET" LLM_VKEY="$LLM_VKEY" TEMPORAL_NS="$TEMPORAL_NS" ANALYTICS_SITE="$ANALYTICS_SITE" CORE_PLATFORM="$PWD/$CORE_PLATFORM" ./bootstrap.sh
${owned.has("casdoor") ? `    - $CORE_PLATFORM/idp/onboard-oidc.sh "$APP" "http://localhost:$FRONTEND_PORT/auth/callback"
    - $CORE_PLATFORM/idp/seed-test-users.sh "$APP" ${personas}
` : ""}
# --- Gates (blocking) ---
fitness:
  extends: .gate
  script:
    - bun "$HARNESS/src/cli.ts" fitness .

lint:
  extends: .gate
  script:
    - bunx @biomejs/biome@2.2.4 ci .
    - |
      for s in $SERVICES; do
        (cd "$s" && bun install --frozen-lockfile && bunx tsc --noEmit) || exit 1
      done

test:
  extends: .gate
  script:
    - |
      for s in $SERVICES; do
        (cd "$s" && bun install --frozen-lockfile && bun test) || exit 1
      done

audit:
  extends: .gate
  script:
    - |
      for s in $SERVICES; do
        (cd "$s" && bun audit --audit-level=high) || exit 1
      done

secrets:
  extends: .gate
  script:
    - |
      if gitleaks version >/dev/null 2>&1; then
        gitleaks detect --source . --redact --no-git
      else
        podman run --rm -v "$PWD:/repo:Z" docker.io/zricethezav/gitleaks:v8.24.2 detect --source /repo --redact --no-git
      fi

# --- Build + image: single-stage Dockerfiles that only COPY ---
${tsServices.map((s) => `build-${s}:
  extends: .on-start
  stage: app-build
  script:
    - cd ${s} && bun install --production --frozen-lockfile
`).join("\n")}
${services.map((s) => `image-${s}:
  extends: .podman-image
  variables: { SERVICE: ${s} }
`).join("\n")}
deploy:
  extends: .on-start
  stage: app-deploy
  script:
    - podman compose -p "$APP" up -d --force-recreate

verify:
  extends: .on-start
  stage: app-verify
  script:
    - |
      set -e
      URLS="${ready.join(" ")}"
      for _ in $(seq 1 60); do
        ok=1
        for u in $URLS; do curl -sf "$u" >/dev/null || { ok=0; break; }; done
        [ "$ok" = "1" ] && break
        sleep 1
      done
      for u in $URLS; do curl -sf "$u" >/dev/null && echo "  OK    $u" || { echo "  FAIL  $u"; exit 1; }; done

stop:
  stage: app-stop
  rules:
    - if: $ACTION == "stop"
  script:
    - podman compose -p "$APP" down
`;
}

export function claudeSettings(): string {
  return `${JSON.stringify(
    {
      hooks: {
        PreToolUse: [
          {
            matcher: "Write|Edit|MultiEdit|Bash",
            hooks: [{ type: "command", command: 'bun "$CLAUDE_PROJECT_DIR/../harness/hooks/guard.ts"' }],
          },
        ],
      },
    },
    null,
    2,
  )}\n`;
}

/** Writes the harness-owned scaffold. Builder files (api/, frontend/) are never touched. */
export function writeScaffold(appDir: string, brief: Brief, bill: Bill, core: string) {
  mkdirSync(join(appDir, ".claude"), { recursive: true });
  writeFileSync(join(appDir, "podman-compose.yml"), composeYml(brief, bill));
  writeFileSync(join(appDir, ".gitlab-ci.yml"), gitlabCiYml(brief, bill));
  writeFileSync(join(appDir, ".claude", "settings.json"), claudeSettings());
  copyFileSync(join(core, "templates", "bootstrap.sh"), join(appDir, "bootstrap.sh"));
  chmodSync(join(appDir, "bootstrap.sh"), 0o755);
  // The CCoE Biome config, plus the harness-written state, which is not the builder's code.
  const biome = JSON.parse(readFileSync(join(core, "templates", "biome.json"), "utf8"));
  // (.gitlab-ci-local copies biome.json into its builds/ — a second "root" config Biome refuses.)
  biome.files.includes.push("!**/.harness", "!**/artifacts", "!**/openspec", "!**/.claude", "!**/.gitlab-ci-local");
  writeFileSync(join(appDir, "biome.json"), `${JSON.stringify(biome, null, 2)}\n`);
  // The agents and skills the builder session uses — copied, so the app repo stands alone.
  for (const sub of ["skills/brief-check", "skills/decide", "agents"]) {
    const src = join(HARNESS_DIR, ".claude", sub);
    if (!existsSync(src)) continue;
    const dst = join(appDir, ".claude", sub);
    mkdirSync(dst, { recursive: true });
    for (const f of new Bun.Glob("*.md").scanSync(src)) copyFileSync(join(src, f), join(dst, f));
  }
}
